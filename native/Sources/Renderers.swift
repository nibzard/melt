enum MarkdownDocument {
    static func render(_ text: String) -> NSAttributedString {
        guard let parsed = try? AttributedString(markdown: text) else { return NSAttributedString(string: text) }
        let result = NSMutableAttributedString(string: "")
        var previousBlock: Int?
        for run in parsed.runs {
            let components = run.presentationIntent?.components ?? []
            let block = components.first?.identity
            if let previous = previousBlock, block != previous { result.append(NSAttributedString(string: "\n\n")) }
            previousBlock = block
            var font = NSFont.systemFont(ofSize: 14)
            for component in components {
                if case .header(let level) = component.kind { font = .boldSystemFont(ofSize: CGFloat(max(16, 26 - level * 2))) }
            }
            if let intent = run.inlinePresentationIntent {
                if intent.contains(.code) { font = .monospacedSystemFont(ofSize: 13, weight: .regular) }
                if intent.contains(.stronglyEmphasized) { font = NSFont(descriptor: font.fontDescriptor.withSymbolicTraits(.bold), size: font.pointSize) ?? font }
                if intent.contains(.emphasized) { font = NSFont(descriptor: font.fontDescriptor.withSymbolicTraits(.italic), size: font.pointSize) ?? font }
            }
            var attributes: [NSAttributedString.Key: Any] = [.font: font, .foregroundColor: NSColor.textColor]
            if let url = run.link, ["https", "http", "mailto"].contains(url.scheme?.lowercased() ?? "") { attributes[.link] = url }
            // Build only text and approved link attributes. Foundation's image
            // URLs, HTML, attachments, and arbitrary URI schemes never load.
            result.append(NSAttributedString(string: String(parsed[run.range].characters), attributes: attributes))
        }
        return result
    }
}

final class PlotScrollView: NSScrollView {
    var resized: (() -> Void)?
    override func layout() {
        super.layout()
        DispatchQueue.main.async { [weak self] in self?.resized?() }
    }
}

final class PlotView: NSObject {
    let view = NSStackView(), scroll = PlotScrollView(), image = NSImageView()
    let provenance = label("", size: 10)
    private var bytes: Data?, artifact = ""
    private var fitting = true
    private(set) var isRendering = false
    override init() {
        super.init()
        view.orientation = .vertical; view.alignment = .leading; view.spacing = 5
        scroll.hasVerticalScroller = true; scroll.hasHorizontalScroller = true
        scroll.allowsMagnification = true; scroll.minMagnification = 0.05; scroll.maxMagnification = 16
        scroll.resized = { [weak self] in
            if self?.fitting == true { self?.fitImage() }
        }
        image.imageScaling = .scaleNone; scroll.documentView = image
        let controls = NSStackView(views: [
            ClickButton("−") { [weak self] in self?.zoom(0.8) },
            ClickButton("+") { [weak self] in self?.zoom(1.25) },
            ClickButton("Fit") { [weak self] in self?.fit() },
            ClickButton("Export PNG…") { [weak self] in self?.export() }])
        for item in [controls, scroll, provenance] { view.addArrangedSubview(item) }
        scroll.widthAnchor.constraint(equalTo: view.widthAnchor).isActive = true
        scroll.heightAnchor.constraint(greaterThanOrEqualToConstant: 100).isActive = true
    }
    func zoom(_ factor: CGFloat) {
        fitting = false
        scroll.magnification = min(16, max(0.05, scroll.magnification * factor))
    }
    func fit() {
        fitting = true
        fitImage()
    }
    private func fitImage() {
        guard image.frame.width > 0, image.frame.height > 0 else { return }
        // Clip bounds are already transformed by magnification. Use the
        // viewport frame to avoid feeding the previous zoom back into fit.
        let size = scroll.contentView.frame.size
        guard size.width > 0, size.height > 0 else { return }
        let scale = min(16, max(0.05, min(size.width / image.frame.width, size.height / image.frame.height)))
        if abs(scroll.magnification - scale) > 0.001 {
            scroll.setMagnification(scale, centeredAt: NSPoint(x: image.frame.midX, y: image.frame.midY))
        }
    }
    func update(_ pane: Object, title: String) {
        let hash = string(pane["artifact"]), path = string(pane["imagePath"])
        guard hash != artifact else { return }
        artifact = hash; isRendering = true
        image.image = nil; bytes = nil
        image.setAccessibilityLabel(title)
        let origin = object(pane["origin"])
        let originText = origin["runId"].map { "Generated by run \($0)" } ?? "Imported image"
        provenance.stringValue = "Loading saved plot…"
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let decoded: (Data, NSBitmapImageRep)? = {
                let fd = Darwin.open(path, O_RDONLY | O_NOFOLLOW | O_NONBLOCK)
                guard fd >= 0 else { return nil }
                let handle = FileHandle(fileDescriptor: fd, closeOnDealloc: true)
                defer { try? handle.close() }
                var facts = stat()
                guard fstat(fd, &facts) == 0, facts.st_mode & S_IFMT == S_IFREG,
                      facts.st_size > 0, facts.st_size <= 1_073_741_824,
                      let data = try? handle.readToEnd(),
                      "sha256:" + SHA256.hash(data: data).map({ String(format: "%02x", $0) }).joined() == hash,
                      let rep = NSBitmapImageRep(data: data), rep.pixelsWide <= 16_384,
                      rep.pixelsHigh <= 16_384, rep.pixelsWide * rep.pixelsHigh <= 64_000_000 else { return nil }
                return (data, rep)
            }()
            DispatchQueue.main.async {
                guard let self = self, self.artifact == hash else { return }
                defer { self.isRendering = false }
                guard let (data, rep) = decoded else {
                    self.image.image = nil; self.bytes = nil
                    self.artifact = ""
                    self.provenance.stringValue = "The saved PNG is unavailable or failed validation."
                    return
                }
                self.bytes = data
                self.provenance.stringValue = originText
                let size = NSSize(width: rep.pixelsWide, height: rep.pixelsHigh)
                let picture = NSImage(size: size); picture.addRepresentation(rep)
                self.image.image = picture; self.image.frame = NSRect(origin: .zero, size: size)
                self.fit()
            }
        }
    }
    func export(to url: URL) throws {
        guard let bytes = bytes else { throw HostError.message("No validated PNG is available to export.") }
        try bytes.write(to: url, options: .atomic)
    }
    private func export() {
        let panel = NSSavePanel(); panel.allowedContentTypes = [.png]; panel.nameFieldStringValue = "Plot.png"
        guard panel.runModal() == .OK, let url = panel.url else { return }
        do { try export(to: url) } catch { provenance.stringValue = error.localizedDescription }
    }
}
